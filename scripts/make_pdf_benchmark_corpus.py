"""Generate redistributable, explicitly synthetic PDF structure fixtures."""

import hashlib
import json
from pathlib import Path
import fitz


def main():
    root = Path("tests/fixtures/pdf_benchmark")
    root.mkdir(parents=True, exist_ok=True)
    corpus = []
    definitions = {
        "digital": [
            "Introduction",
            "Alpha evidence establishes a baseline.",
            "Results",
            "Beta evidence confirms the result.",
        ],
        "columns": [
            "Introduction",
            "Left column starts here.",
            "Left column ends here.",
            "Right column starts here.",
            "Right column ends here.",
        ],
        "table": ["Results", "Group  Count", "Alpha  12", "Beta  24"],
        "bibliography": [
            "Introduction",
            "Evidence cites Smith 2024.",
            "References",
            "Smith 2024. A synthetic reference.",
        ],
        "scan": [
            "Introduction",
            "Scanned evidence requires OCR.",
            "Results",
            "The measured count is 12.",
        ],
    }
    for name, lines in definitions.items():
        doc = fitz.open()
        page = doc.new_page()
        expected = []
        for i, line in enumerate(lines):
            x = 310 if name == "columns" and i >= 3 else 50
            y = 60 + (i - 3 if name == "columns" and i >= 3 else i) * 35
            page.insert_text((x, y), line, fontsize=12)
            expected.append(
                {"text": line, "page": 1, "bbox": [x, y - 14, x + 260, y + 4]}
            )
        if name == "scan":
            pix = page.get_pixmap(matrix=fitz.Matrix(2, 2))
            scanned = fitz.open()
            target = scanned.new_page(width=page.rect.width, height=page.rect.height)
            target.insert_image(target.rect, stream=pix.tobytes("png"))
            doc.close()
            doc = scanned
        raw = doc.tobytes(no_new_id=True)
        doc.close()
        path = root / (name + ".pdf")
        path.write_bytes(raw)
        corpus.append(
            {
                "path": str(path),
                "sha256": hashlib.sha256(raw).hexdigest(),
                "kind": name,
                "expected": expected,
                "table_cells": ["Group", "Count", "Alpha", "12", "Beta", "24"]
                if name == "table"
                else [],
                "references": ["Smith 2024. A synthetic reference."]
                if name == "bibliography"
                else [],
            }
        )
    (root / "manifest.json").write_text(
        json.dumps(
            {
                "license": "CC0-1.0",
                "provenance": "Original synthetic fixtures generated by make_pdf_benchmark_corpus.py; authored expected structure, not independent annotations of scientific papers.",
                "documents": corpus,
            },
            indent=2,
        )
        + "\n"
    )


if __name__ == "__main__":
    main()
